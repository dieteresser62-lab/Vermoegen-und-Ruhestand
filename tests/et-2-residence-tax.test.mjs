import { measurementInputs } from './helpers/ek-1b-measurement.mjs';
import { initMcRunState, simulateOneYear } from '../app/simulator/simulator-engine-wrapper.js';
import { EngineAPI } from '../engine/index.mjs';
import { inheritancePreview, readPartnership, residenceAnnualValue, PARTNERSHIP_KEY } from '../app/profile/household-partnership.js';
import { readImmobilien, writeImmobilien, IMMOBILIEN_KEY } from '../app/profile/profile-immobilien.js';
import { createMusterHaushaltRecords } from '../app/demo/muster-haushalt.js';
import { exportProfilesBundle, importProfilesBundle } from '../app/profile/profile-bundle-io.js';
import { buildFullPersistenceBackup, normalizeFullPersistenceBackup, validatePersistenceDomainRecords } from '../app/shared/persistence-backup.js';
import { renderProtocolTable } from '../app/simulator/protocol-renderer.js';
import { protocolCashflowBreakdown } from '../app/simulator/protocol-cashflows.js';
import { testamentFields } from '../app/tranches/tranchen-manager-testament.js';

const base = await measurementInputs(0, 'martin-petra', '2026-10-23', 'testament');
const year = { jahr: 2000, inflation: 2, rendite: 0, gold_eur_perf: 0, zinssatz: 0 };
const alive = { p1Alive: false, p2Alive: true };
const run = (inputs, state = initMcRunState(inputs), index = 0, household = alive, data = year) =>
    simulateOneYear(state, inputs, data, index, null, 0, household, 1, EngineAPI);
const inputs = structuredClone(base);
inputs.partnership.testament.muster_martin.residenceTax = 'annual';
const death = run(inputs), estate = death.logData.inheritance;
assertEqual(death.kind, 'success', 'Jährliche Wahl: echter Todesjahr-Lauf');
assertClose(estate.tax, Math.max(0, estate.inherited - 20000) * .3, 1e-7, 'Im Todesjahr nur Geldanteil nach Freibetrag');
assertEqual(death.logData.wohnrechtsteuer, undefined, 'Erste Vorauszahlung erst im Folgejahr');
assertClose(estate.residenceTax.annualTax, 612000 * .04 * .3, 1e-7, 'Jahressteuer aus Wert im Todesjahr');
const next = run(inputs, death.newState, 1);
assertEqual(next.kind, 'success', 'Folgejahr rechnet die Vorauszahlung');
assertClose(next.logData.wohnrechtsteuer, estate.residenceTax.annualTax, 1e-7, 'Jahreszahlung bleibt trotz weiterer Inflation nominal fest');
assertEqual(JSON.stringify(death.newState.portfolio.residenceTax), JSON.stringify({ ...estate.residenceTax, profileId: 'muster_petra' }), 'Folgejahr verändert den vorherigen Steuerzustand nicht');
assertClose(next.logData.portfolio_flow_delta, 0, .05, 'Jahreszahlung mit Jahressteuer vollständig bilanziert');
const html = renderProtocolTable([death.logData, next.logData], { source: 'mc', inputs });
assert(html.includes('Steuer Wohnrecht (§ 23)') && html.includes('Vorauszahlung zu Jahresbeginn'), 'Protokoll zeigt Zahlung und Erklärung');
assert(protocolCashflowBreakdown(next.logData, { inputs }).expenses.some(item => item.label === 'Steuer Wohnrecht (§ 23)'), 'Jahreszahlung erscheint als Partnerausgabe');
const married = structuredClone(inputs);
married.partnership.status = 'married'; married.partnership.marriedInheritance = { muster_martin: 100 };
married.partnership.testament.muster_martin = { home: 'residence', residenceTax: 'annual' };
const marriedDeath = run(married).logData.inheritance;
assertEqual(marriedDeath.residenceTax.rate, .15, 'Tarifstufe richtet sich auch bei Ehe nach dem Gesamterwerb mit Wohnrecht');
assertClose(marriedDeath.tax, (marriedDeath.inherited - 500000) * .15, 1e-7, 'Erhöhter Gesamterwerbs-Satz gilt für den sofort steuerpflichtigen Geldanteil');

const noMoney = structuredClone(inputs);
noMoney.partnership.testament.muster_martin = { home: 'residence', residenceTax: 'annual', maximumPercent: 0 };
const freeDeath = run(noMoney), first = run(noMoney, freeDeath.newState, 1), second = run(noMoney, first.newState, 2);
assertEqual(freeDeath.logData.erbschaftsteuer, 0, 'Kein Geldanteil: Freibetrag bleibt für Jahreswerte');
assertClose(first.logData.wohnrechtsteuer, (24480 - 20000) * .3, 1e-7, 'Aufzehrmethode: erster Jahreswert teilweise steuerfrei');
assertClose(second.logData.wohnrechtsteuer, 24480 * .3, 1e-7, 'Nach Aufzehrung voller Jahreswert');
const rented = structuredClone(noMoney);
rented.home.find(home => home.profileId === 'muster_martin').ortsueblicheMiete = 1500;
const rentDeath = run(rented), rentFirst = run(rented, rentDeath.newState, 1), rentSecond = run(rented, rentFirst.newState, 2);
assertClose(rentDeath.logData.inheritance.residenceTax.annualValue, 18360, 1e-7, 'Mietwert wächst bis zum Todesjahr mit dem Immobilienstand');
assertEqual(rentFirst.logData.wohnrechtsteuer, 0, 'Erster kleiner Jahreswert ganz steuerfrei');
assertClose(rentSecond.logData.wohnrechtsteuer, (18360 - 1640) * .3, 1e-7, 'Freibetragsrest läuft über mehrere Jahre');
assertEqual(residenceAnnualValue(600000), 24000, 'Leere Miete bleibt bei 4 Prozent');
assertEqual(residenceAnnualValue(600000, 0), 0, 'Gesetzte Nullmiete ist kein leeres Feld');
assertEqual(residenceAnnualValue(600000, 10000), 600000 / 18.6, 'Gesetzte Miete bleibt durch Wert/18,6 begrenzt');
const preview = inheritancePreview(600000, 600000, 100 / 3, { exemptHome: 600000, partnerAge: 60, testament: inputs.partnership.testament.muster_martin });
assertEqual(preview.tax, 54000, 'Vorschau: sofort nur Geldsteuer');
assertEqual(preview.residenceTax.annualTax, 7200, 'Vorschau: jährliche Steuer');
const homeCare = { ...alive, care: { p2: { active: true, grade: 3 } } };
const careInputs = { ...inputs, pflegeKostenStaffelPreset: 'custom', pflegeGradeConfigs: { ...inputs.pflegeGradeConfigs, 3: { ...inputs.pflegeGradeConfigs?.[3], careForm: 'residential' } } };
const care = run(careInputs, death.newState, 1, homeCare);
assertEqual(care.logData.wohnrechtsteuer, undefined, 'Heim beendet Zahlung auch vor Pflegegrad 4');
assert(Object.values(care.newState.portfolio.homeInheritance).every(home => !home.residenceActive), 'Heim beendet das Wohnrecht');
const afterCare = run(careInputs, care.newState, 2);
assertEqual(afterCare.logData.wohnrechtsteuer, undefined, 'Beendetes Wohnrecht beginnt nach Heim nicht erneut');
const dead = run(inputs, death.newState, 1, { p1Alive: false, p2Alive: false });
assertEqual(dead.logData.wohnrechtsteuer, undefined, 'Tod beendet Jahreszahlung');

const cashless = structuredClone(death.newState);
cashless.portfolio.personAccounts.forEach(person => { person.tagesgeld = 0; person.geldmarktEtf = 0; });
cashless.portfolio.depotTranchesGeldmarkt = [];
cashless.portfolio.liquiditaet = 0;
const sale = run(inputs, cashless, 1);
assertEqual(sale.kind, 'success', 'Vorauszahlung ohne Tagesgeld über Depotverkauf');
assert(sale.logData.residenceTaxPayment.sources.length > 0, 'Verkauf für Jahressteuer ist tatsächlich ausgeführt');
assertClose(sale.logData.portfolio_flow_delta, 0, .05, 'Verkauf und Kapitalertragsteuer bleiben bilanziert');
const savingInputs = { ...inputs, accumulationPhase: { enabled: true, sparrate: 1000 }, transitionYear: 5 };
const saving = run(savingInputs, death.newState, 1);
assertEqual(saving.kind, 'success', 'Jahreszahlung auch im Ansparpfad');
assertClose(saving.logData.wohnrechtsteuer, estate.residenceTax.annualTax, 1e-7, 'Ansparpfad übernimmt dieselbe Vorauszahlung');
assertClose(saving.logData.portfolio_flow_delta, 0, .05, 'Ansparpfad bilanziert die Vorauszahlung');
const explicit = structuredClone(base); explicit.partnership.testament.muster_martin.residenceTax = 'immediate';
assertEqual(JSON.stringify(run(base)), JSON.stringify(run(explicit)), 'Fehlende Wahl und explizit sofort: ganze Jahresrechnung bytegleich');
assert(!testamentFields('a', 0, {}).includes('data-testament="residenceTax"'), 'Steuerwahl nur beim Wohnrecht');
assert(testamentFields('a', 0, { home: 'residence' }).includes('value="immediate" selected'), 'Steuerwahl hat Vorgabe sofort');
assertEqual(JSON.stringify(readPartnership(base.partnership)), JSON.stringify(base.partnership), 'Altbestand lädt ohne zusätzliche gespeicherte Felder');
const homes = [{ id: 'muster', bezeichnung: 'Musterhaus', nutzung: 'selbst', wert: 600000, stand: '2026-10', mieteNetto: 0, anpassung: 'keine', ortsueblicheMiete: 1500 }];
assertEqual(readImmobilien(writeImmobilien(homes))[0].ortsueblicheMiete, 1500, 'Immobilienrecord erhält neue Miete');
const records = createMusterHaushaltRecords('2026-10-23', 'martin-petra', 'testament');
records[PARTNERSHIP_KEY] = JSON.stringify(inputs.partnership);
const registry = JSON.parse(records.rs_profiles_v1);
registry.profiles.muster_martin.data[IMMOBILIEN_KEY] = writeImmobilien(homes);
records.rs_profiles_v1 = JSON.stringify(registry);
const storage = { records, get length() { return Object.keys(this.records).length; }, key(i) { return Object.keys(this.records)[i] ?? null; },
    getItem(key) { return this.records[key] ?? null; }, setItem(key, value) { this.records[key] = String(value); }, removeItem(key) { delete this.records[key]; } };
const target = { ...storage, records: {} };
assert(importProfilesBundle(exportProfilesBundle({ storage }), { storage: target }).ok, 'Profilimport mit beiden neuen Feldern');
assertEqual(target.records[PARTNERSHIP_KEY], records[PARTNERSHIP_KEY], 'Profilimport erhält jährliche Wahl');
assertEqual(target.records.rs_profiles_v1, records.rs_profiles_v1, 'Profilimport erhält ortsübliche Miete');
for (const schemaVersion of [1, 2]) {
    const backup = buildFullPersistenceBackup({ storage }); backup.schemaVersion = schemaVersion;
    const restored = normalizeFullPersistenceBackup(backup);
    assert(restored.ok, `Vollsicherung Schema ${schemaVersion} mit beiden neuen Feldern`);
    assertEqual(restored.backup.records.rs_profiles_v1, records.rs_profiles_v1, 'Vollsicherung erhält Miete ohne Migration der alten Werte');
    assertEqual(restored.backup.records[PARTNERSHIP_KEY], records[PARTNERSHIP_KEY], 'Vollsicherung erhält jährliche Steuerwahl');
}
const oldHomes = homes.map(({ ortsueblicheMiete, ...home }) => home);
assertEqual(writeImmobilien(readImmobilien(writeImmobilien(oldHomes))), writeImmobilien(oldHomes), 'Alte Immobilienbytes bleiben ohne neues Feld erhalten');
assertEqual(validatePersistenceDomainRecords({ ...records, [PARTNERSHIP_KEY]: JSON.stringify({ ...inputs.partnership, testament: { muster_martin: { home: 'residence', residenceTax: 'invalid' } } }) }).ok, false, 'Import weist ungültige Steuerwahl zurück');
