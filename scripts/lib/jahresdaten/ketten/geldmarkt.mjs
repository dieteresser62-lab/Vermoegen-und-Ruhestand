/**
 * Kette Geldmarkt (german-cash-money-market-chain): Rechenregel, Modultext und Lieferung aus dem Original.
 *
 * Rechenregel Jahr Y: Jahresdurchschnitt des Tagesgeldsatzes (seit Oktober 2019 EURSTR) in Prozent mit zwei
 * Stellen, unverändert als Jahresrendite. Bis 2025 ist das der veröffentlichte Bundesbank-Wert („aus Original“,
 * auch für die Rückwärtsprobe); neue Jahre liefert der Leser leser/geldmarkt.mjs als Mittel der €STR-Tageswerte.
 * Das Bauskript nutzt dieselbe Regel.
 */
import fs from 'node:fs';
import path from 'node:path';
import { jsonAusModul } from '../modultext.mjs';
import { sha256, sha256CanonicalCodepoint } from '../kanonisch.mjs';
import { einheitenFuer, lieferungBauen } from '../lieferung.mjs';

const MODUL = 'app/simulator/german-cash-money-market-chain.js';
const START = 'export const GERMAN_CASH_MONEY_MARKET_CHAIN = deepFreeze(';
const ENDE = ');\n\nexport const GERMAN_CASH_MONEY_MARKET_ANNUAL_RETURNS';
const LAYOUT = 'data/historical/german-cash-money-market-chain/originals/bundesbank-money-market-pages-15-16-layout.txt';
const ZEILE = /^\s*(\d{4})\s+(-\s*)?(\d+\.\d+)(?:\s|$)/;

export const KETTE = Object.freeze({
    id: 'german-cash-money-market-chain',
    seriesId: 'zinssatz_de',
    label: 'Geldmarkt',
    dateien: Object.freeze([MODUL]),
    jahresfelder: Object.freeze(['annualReturnsPct']),
    serienfeld: 'annualReturnsPct',
    periodenFuer: jahr => Object.freeze({ werte: String(jahr), anschluss: String(jahr - 1) }),
    werte: Object.freeze({ jahresmittel: { einheit: 'prozent' }, monatsmittel: { optional: true, einheit: 'prozent' } }),
    beschreibung: Object.freeze({
        jahresmittel: 'Prozent p. a., Jahresdurchschnitt des Tagesgeldsatzes (EURSTR), zwei Stellen',
        monatsmittel: 'Prozent p. a., Durchschnitt der zwölf Monatsdurchschnitte'
    }),
    anschluss: Object.freeze({
        toleranz: Object.freeze({ jahresmittel: 0.005 }),
        regel: 'Jahresmittel Y−1 gegen gespeicherten Wert Y−1; Toleranz 0,005 (halbe zweite Stelle)'
    })
});

/** @param {string} root @returns {any} */
export function lesen(root) {
    return jsonAusModul(root, MODUL, START, ENDE);
}

/** @param {any} artifact @returns {Map<string, string>} */
export function schreiben(artifact) {
    return new Map([[MODUL, `/**
 * Generated by scripts/build-german-cash-money-market-chain.mjs.
 * Do not edit by hand.
 */
"use strict";

function deepFreeze(value, seen = new WeakSet()) {
    if (value === null || typeof value !== 'object' || seen.has(value)) return value;
    seen.add(value);
    for (const child of Object.values(value)) deepFreeze(child, seen);
    return Object.freeze(value);
}

export const GERMAN_CASH_MONEY_MARKET_CHAIN = deepFreeze(${JSON.stringify(artifact, null, 2)});

export const GERMAN_CASH_MONEY_MARKET_ANNUAL_RETURNS =
    GERMAN_CASH_MONEY_MARKET_CHAIN.annualReturnsPct;
`]]);
}

/** Rechenregel (Bau und Fortschreibung): der veröffentlichte Jahresdurchschnitt gilt unverändert. @param {{jahresmittel: number}} werte */
export function geldmarktJahreswert({ jahresmittel }) {
    return jahresmittel;
}

/** @param {any} chain @returns {number} */
export function endjahr(chain) {
    return chain.coverage.endYear;
}

/** @param {any} chain @param {number} year */
export function endjahrSetzen(chain, year) {
    chain.coverage.endYear = year;
    chain.coverage.yearCount = year - chain.coverage.startYear + 1;
    chain.currencyRegimes[chain.currencyRegimes.length - 1].endYear = year;
    chain.qualitySegments[chain.qualitySegments.length - 1].endYear = year;
    chain.hashes.annualReturnHash = sha256CanonicalCodepoint(chain.annualReturnsPct);
}

/** @param {any} _chain @param {any} lieferung @returns {Record<string, number>} */
export function zeileBerechnen(_chain, lieferung) {
    return { annualReturnsPct: geldmarktJahreswert(lieferung.werte) };
}

/** @param {any} chain @param {number} year */
export function gespeichert(chain, year) {
    const jahresmittel = chain.annualReturnsPct[year];
    return Number.isFinite(jahresmittel) ? { jahresmittel } : null;
}

/** @param {any} lieferung @returns {{regel: string, ok: boolean, text: string}[]} */
export function plausibilitaet(lieferung) {
    const { jahresmittel, monatsmittel } = lieferung.werte;
    const hundertstel = jahresmittel * 100;
    const ergebnis = [{
        regel: 'Jahresmittel mit zwei Stellen',
        ok: Math.abs(hundertstel - Math.round(hundertstel)) < 1e-9,
        text: `Jahresmittel ${jahresmittel} %`
    }];
    if (Number.isFinite(monatsmittel)) {
        const abstand = Math.abs(jahresmittel - monatsmittel);
        ergebnis.push({ regel: 'Abstand zum Monatsmittel höchstens 0,005', ok: abstand <= 0.005 + 1e-12, text: `Monatsmittel ${monatsmittel} %, Abstand ${abstand.toFixed(4)}` });
    }
    return ergebnis;
}

/**
 * Lieferung Y aus dem festgeschriebenen Layouttext der Bundesbank-Langreihe (Rückwärtsprobe, offline).
 * @param {string} root @param {number} year
 */
export function lieferungAusOriginalen(root, year) {
    const original = fs.readFileSync(path.join(root, LAYOUT));
    const abschnitt = original.toString('utf8').split('\f').find(section => section.includes('Money market rates from 1999'));
    if (!abschnitt) throw new Error('Bundesbank-Layouttext ohne Tabelle ab 1999.');
    const zeilen = abschnitt.split(/\r?\n/);
    const zeileFuer = y => {
        const treffer = zeilen.filter(line => Number(line.match(ZEILE)?.[1]) === y);
        if (treffer.length !== 1) throw new Error(`Bundesbank-Layouttext: Jahr ${y} kommt ${treffer.length}-mal vor.`);
        const match = treffer[0].match(ZEILE);
        return { zeile: treffer[0], wert: Number(`${match[2] ? '-' : ''}${match[3]}`) };
    };
    const vorjahr = zeileFuer(year - 1);
    const jahr = zeileFuer(year);
    const titel = zeilen.find(line => line.includes('Money market rates from 1999')).trim();
    const chain = lesen(root);
    return lieferungBauen({
        kette: KETTE.id,
        jahr: year,
        werte: { jahresmittel: jahr.wert },
        einheit: einheitenFuer(KETTE, { jahresmittel: true }),
        anschluss: { jahr: year - 1, werte: { jahresmittel: vorjahr.wert } },
        perioden: KETTE.periodenFuer(year),
        quelle: {
            name: 'Deutsche Bundesbank, Lange Zeitreihen, Geldmarktsätze (Tagesgeld), Seiten 15–16',
            url: chain.sourceFiles.bundesbankPdf.sourceUrl,
            abrufdatum: chain.sourceFiles.bundesbankPdf.dataAsOf,
            veroeffentlichungsstand: `Datenstand ${chain.sourceFiles.bundesbankPdf.dataAsOf}`
        },
        methode: 'aus Original: veröffentlichter Jahresdurchschnitt Tagesgeld (erste Spalte) aus dem festgeschriebenen Layouttext',
        lieferant: 'skript',
        status: 'endgueltig',
        rohdateien: [{
            datei: 'rohauszug-bundesbank-tagesgeld.txt', inhalt: Buffer.from(`${titel}\n${vorjahr.zeile}\n${jahr.zeile}\n`, 'utf8'), art: 'auszug',
            originalDatei: LAYOUT, originalSha256: sha256(original)
        }]
    });
}
