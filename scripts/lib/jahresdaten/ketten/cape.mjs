/**
 * Kette CAPE (us-shiller-cape-chain): Rechenregel, Modultext und Lieferung aus dem Original.
 *
 * Rechenregel Renditejahr Y: konventionelles CAPE (Shiller, Spalte „CAPE“) vom Dezember Y−1, unverändert.
 * Die Shiller-Datei hat keine offene Lizenz; eine Lieferung enthält nur einen Auszug der benötigten
 * Zeilen und den SHA-256 der Originaldatei. Das Bauskript nutzt dieselbe Beobachtungsregel.
 */
import fs from 'node:fs';
import path from 'node:path';
import { jsonAusModul } from '../modultext.mjs';
import { sha256, sha256CanonicalLocale } from '../kanonisch.mjs';
import { einheitenFuer, lieferungBauen } from '../lieferung.mjs';
import { readBiff8Sheet } from '../../biff8-numeric-sheet.mjs';

const MODUL = 'app/simulator/us-shiller-cape-chain.js';
const START = 'export const US_SHILLER_CAPE_CHAIN = deepFreeze(';
const ENDE = ');\n\nexport const US_SHILLER_CAPE_BY_RETURN_YEAR';
const ORIGINAL = 'data/historical/us-shiller-cape-chain/originals/shiller-ie-data-2026-08-01.xls';

export const KETTE = Object.freeze({
    id: 'us-shiller-cape-chain',
    seriesId: 'cape',
    label: 'CAPE',
    dateien: Object.freeze([MODUL]),
    jahresfelder: Object.freeze(['observationsByReturnYear', 'annualDecisionSignals']),
    serienfeld: 'annualDecisionSignals',
    periodenFuer: jahr => Object.freeze({ werte: `${jahr - 1}-12`, anschluss: `${jahr - 2}-12` }),
    werte: Object.freeze({ cape: { einheit: 'verhaeltnis' } }),
    beschreibung: Object.freeze({ cape: 'Verhältnis, konventionelles CAPE (Shiller), Monatswert Dezember des Vorjahres' }),
    anschluss: Object.freeze({
        toleranz: Object.freeze({ cape: 0.05 }),
        regel: 'CAPE Dezember Y−2 (Renditejahr Y−1) gegen den gespeicherten Wert; Toleranz 0,05 wie in der Liveprobe'
    })
});

/** @param {string} root @returns {any} */
export function lesen(root) {
    return jsonAusModul(root, MODUL, START, ENDE);
}

/** @param {any} artifact @returns {Map<string, string>} */
export function schreiben(artifact) {
    return new Map([[MODUL, `/**
 * Generated by scripts/build-us-shiller-cape-chain.mjs.
 * Do not edit by hand.
 */
"use strict";

function deepFreeze(value, seen = new WeakSet()) {
    if (value === null || typeof value !== 'object' || seen.has(value)) return value;
    seen.add(value);
    for (const child of Object.values(value)) deepFreeze(child, seen);
    return Object.freeze(value);
}

export const US_SHILLER_CAPE_CHAIN = deepFreeze(${JSON.stringify(artifact, null, 2)});

export const US_SHILLER_CAPE_BY_RETURN_YEAR =
    US_SHILLER_CAPE_CHAIN.annualDecisionSignals;
`]]);
}

/** Beobachtung eines Renditejahres (Bau und Fortschreibung). @param {number} returnYear @param {number} value */
export function capeBeobachtung(returnYear, value) {
    const observationYear = returnYear - 1;
    return {
        value,
        observationYear,
        observationMonth: 12,
        asOfYear: observationYear,
        decisionYear: returnYear
    };
}

/** @param {any} chain @returns {number} */
export function endjahr(chain) {
    return chain.coverage.endReturnYear;
}

/** @param {any} chain @param {number} year */
export function endjahrSetzen(chain, year) {
    chain.coverage.endReturnYear = year;
    chain.coverage.yearCount = year - chain.coverage.startReturnYear + 1;
    chain.coverage.sourceObservationEnd = `${year - 1}-12`;
    chain.qualitySegments[chain.qualitySegments.length - 1].endYear = year;
    chain.hashes.annualDecisionSignalHash = sha256CanonicalLocale(chain.annualDecisionSignals);
    chain.hashes.observationContractHash = sha256CanonicalLocale(chain.observationsByReturnYear);
}

/** @param {any} _chain @param {any} lieferung @returns {Record<string, any>} */
export function zeileBerechnen(_chain, lieferung) {
    const value = lieferung.werte.cape;
    if (!(value > 0)) throw new Error('CAPE muss positiv sein.');
    return { observationsByReturnYear: capeBeobachtung(lieferung.jahr, value), annualDecisionSignals: value };
}

/** @param {any} chain @param {number} year */
export function gespeichert(chain, year) {
    const cape = chain.annualDecisionSignals[year];
    return Number.isFinite(cape) ? { cape } : null;
}

/** @param {any} lieferung @param {any} chain @returns {{regel: string, ok: boolean, text: string}[]} */
export function plausibilitaet(lieferung, chain) {
    const { cape } = lieferung.werte;
    const vorjahr = chain.annualDecisionSignals[lieferung.jahr - 1];
    const sprung = Math.abs((cape / vorjahr) - 1);
    return [
        { regel: 'CAPE 5–60', ok: cape >= 5 && cape <= 60, text: `CAPE ${cape.toFixed(2)}` },
        { regel: 'Sprung zum Vorjahr unter 30 %', ok: sprung < 0.3, text: `Vorjahr ${vorjahr.toFixed(2)}, Sprung ${(sprung * 100).toFixed(1)} %` }
    ];
}

/** @param {number} rawDate */
function shillerMonat(rawDate) {
    if (!Number.isFinite(rawDate)) return null;
    const year = Math.floor(rawDate + 1e-8);
    const month = Math.round((rawDate - year) * 100);
    return month >= 1 && month <= 12 ? { year, month } : null;
}

/**
 * Lieferung für Renditejahr Y aus der festgeschriebenen Shiller-Arbeitsmappe (Rückwärtsprobe, offline):
 * Dezember Y−1 als Wert, Dezember Y−2 als Anschluss. Ins Repo kommt nur der Auszug dieser Zeilen.
 * @param {string} root @param {number} year
 */
export function lieferungAusOriginalen(root, year) {
    const chain = lesen(root);
    const original = fs.readFileSync(path.join(root, ORIGINAL));
    const { cells, textCells } = readBiff8Sheet(original, chain.method.sourceSheet);
    const header = textCells.get(chain.method.sourceHeaderRowZeroBased);
    if (header?.get(chain.method.sourceDateColumnZeroBased) !== 'Date' || header?.get(chain.method.sourceCapeColumnZeroBased) !== 'CAPE') {
        throw new Error('Shiller-Arbeitsmappe: Spalten Date/CAPE nicht an der festgeschriebenen Stelle.');
    }
    const dezember = new Map();
    for (const row of cells.values()) {
        const rawDate = row.get(chain.method.sourceDateColumnZeroBased);
        const periode = shillerMonat(rawDate);
        if (periode?.month === 12) dezember.set(periode.year, { rawDate, cape: row.get(chain.method.sourceCapeColumnZeroBased) });
    }
    const wertFuer = returnYear => {
        const zeile = dezember.get(returnYear - 1);
        if (!Number.isFinite(zeile?.cape)) throw new Error(`Shiller-Arbeitsmappe: CAPE Dezember ${returnYear - 1} fehlt.`);
        return zeile;
    };
    const auszug = ['Date,CAPE', ...[year - 1, year].map(y => `${wertFuer(y).rawDate},${wertFuer(y).cape}`)].join('\n');
    return lieferungBauen({
        kette: KETTE.id,
        jahr: year,
        werte: { cape: wertFuer(year).cape },
        einheit: einheitenFuer(KETTE, { cape: true }),
        anschluss: { jahr: year - 1, werte: { cape: wertFuer(year - 1).cape } },
        perioden: KETTE.periodenFuer(year),
        quelle: {
            name: 'Robert J. Shiller, U.S. Stock Markets 1871-Present and CAPE Ratio (ie_data.xls), Blatt Data, Spalte CAPE',
            url: 'https://shillerdata.com/',
            abrufdatum: chain.sourceFile.retrievedAt,
            veroeffentlichungsstand: `Daten bis ${chain.sourceFile.sourceMaximumPeriod}`
        },
        methode: 'aus Original: Dezemberwert des Vorjahres aus der festgeschriebenen Shiller-Arbeitsmappe; nur Auszug, keine Originaldatei',
        lieferant: 'skript',
        status: 'endgueltig',
        rohdateien: [{
            datei: 'rohauszug-shiller-cape.csv', inhalt: Buffer.from(`${auszug}\n`, 'utf8'), art: 'auszug',
            originalDatei: ORIGINAL, originalSha256: sha256(original)
        }]
    });
}
