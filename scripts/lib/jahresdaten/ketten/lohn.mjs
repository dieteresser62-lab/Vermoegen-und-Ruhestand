/**
 * Kette Lohn (german-gross-wage-growth-chain): Rechenregel, Modultexte und Lieferung aus dem Original.
 *
 * Rechenregel Jahr Y: veröffentlichte Veränderung des Index der Bruttomonatsverdienste (ohne
 * Sonderzahlungen) zum Vorjahr in Prozent; die Beobachtung hält Indexstand und Veränderung fest.
 * Das Bauskript nutzt dieselbe Beobachtungsregel für alle amtlichen Jahre.
 */
import fs from 'node:fs';
import path from 'node:path';
import { jsonTextZwischen } from '../modultext.mjs';
import { sha256, sha256CanonicalLocale } from '../kanonisch.mjs';
import { einheitenFuer, lieferungBauen } from '../lieferung.mjs';

const ORDNER = 'app/simulator/german-gross-wage-growth-chain';
const CHAIN = `${ORDNER}/chain.js`;
const OBSERVATIONS = `${ORDNER}/observations.js`;
const ANNUAL = `${ORDNER}/annual-growth.js`;
const ORIGINAL_HTML = 'data/historical/german-gross-wage-growth-chain/originals/destatis-bruttomonatsverdienst-index-2026-08-01.html';
const ROW_PATTERN = /<tr><td class="Vorspalte">(\d{4})<\/td><td>([\s\S]*?)<\/td><td>([\s\S]*?)<\/td><\/tr>/g;

export const KETTE = Object.freeze({
    id: 'german-gross-wage-growth-chain',
    seriesId: 'lohn_de',
    label: 'Lohn',
    dateien: Object.freeze([CHAIN, OBSERVATIONS, ANNUAL]),
    jahresfelder: Object.freeze(['observationsByYear', 'annualGrowthPct']),
    serienfeld: 'annualGrowthPct',
    periodenFuer: jahr => Object.freeze({ werte: String(jahr), anschluss: String(jahr - 1) }),
    werte: Object.freeze({ indexstand: { einheit: 'index', basis: true }, veraenderung: { einheit: 'prozent' } }),
    beschreibung: Object.freeze({
        indexstand: 'Index der Bruttomonatsverdienste ohne Sonderzahlungen, Jahr, eine Stelle (Basis laut Quelle)',
        veraenderung: 'Prozent zum Vorjahr, eine Stelle (Destatis)'
    }),
    anschluss: Object.freeze({
        toleranz: Object.freeze({ veraenderung: 0.05, indexstand: 0.05 }),
        regel: 'Veränderung und amtlicher Indexstand Y−1 gegen den gespeicherten Stand (Toleranz 0,05, halbe Veröffentlichungsstufe 0,1); Indexbasis muss gleich sein, sonst Umbasierung'
    })
});

/** @param {string} text @param {string} name */
function tabelle(text, name) {
    const start = `export const ${name} = `;
    const from = text.indexOf(start);
    if (from < 0) throw new Error(`${name} fehlt.`);
    return JSON.parse(text.slice(from + start.length, text.lastIndexOf(';\n')));
}

/** @param {string} root @returns {any} */
export function lesen(root) {
    const read = file => fs.readFileSync(path.join(root, file), 'utf8');
    const metadata = JSON.parse(`${jsonTextZwischen(read(CHAIN), 'export const GERMAN_GROSS_WAGE_GROWTH_CHAIN = deepFreeze(',
        ',\n  "observationsByYear": OBSERVATIONS_BY_YEAR,', CHAIN)}\n}`);
    return { ...metadata, observationsByYear: tabelle(read(OBSERVATIONS), 'OBSERVATIONS_BY_YEAR'), annualGrowthPct: tabelle(read(ANNUAL), 'ANNUAL_GROWTH_PCT') };
}

/** @param {any} artifact @returns {Map<string, string>} */
export function schreiben(artifact) {
    const { observationsByYear, annualGrowthPct, ...metadata } = artifact;
    const header = `// @ts-check
/**
 * Generated by scripts/build-german-gross-wage-growth-chain.mjs.
 * Do not edit by hand.
 */
"use strict";

`;
    // Retain the original indentation of both annual tables byte for byte.
    const table = (name, values) => `${header}export const ${name} = ${
        JSON.stringify(values, null, 2).replace(/\n/g, '\n  ')
    };\n`;
    const chain = `${header}import { OBSERVATIONS_BY_YEAR } from './observations.js';
import { ANNUAL_GROWTH_PCT } from './annual-growth.js';

function deepFreeze(value, seen = new WeakSet()) {
    if (value === null || typeof value !== 'object' || seen.has(value)) return value;
    seen.add(value);
    for (const child of Object.values(value)) deepFreeze(child, seen);
    return Object.freeze(value);
}

export const GERMAN_GROSS_WAGE_GROWTH_CHAIN = deepFreeze(${JSON.stringify(metadata, null, 2).slice(0, -2)},
  "observationsByYear": OBSERVATIONS_BY_YEAR,
  "annualGrowthPct": ANNUAL_GROWTH_PCT
});

export const GERMAN_GROSS_WAGE_GROWTH_PCT =
    GERMAN_GROSS_WAGE_GROWTH_CHAIN.annualGrowthPct;
`;
    return new Map([
        [CHAIN, chain],
        [OBSERVATIONS, table('OBSERVATIONS_BY_YEAR', observationsByYear)],
        [ANNUAL, table('ANNUAL_GROWTH_PCT', annualGrowthPct)]
    ]);
}

/**
 * Amtliche Beobachtung eines Jahres (Bau und Fortschreibung).
 * @param {number} year @param {{indexLevel: number, annualChangePct: number}} sourceObservation
 */
export function lohnBeobachtung(year, sourceObservation) {
    return {
        valuePct: sourceObservation.annualChangePct,
        sourceYear: year,
        evidenceClass: 'official',
        sourceObservation: {
            indexLevel: sourceObservation.indexLevel,
            indexLevelPrecision: 0.1,
            publishedAnnualChangePct: sourceObservation.annualChangePct,
            publishedAnnualChangePrecisionPct: 0.1
        }
    };
}

/** @param {any} chain @returns {number} */
export function endjahr(chain) {
    return chain.coverage.endYear;
}

/** @param {any} chain @param {number} year */
export function endjahrSetzen(chain, year) {
    chain.coverage.endYear = year;
    chain.coverage.yearCount = year - chain.coverage.startYear + 1;
    chain.territorialSegments[chain.territorialSegments.length - 1].endYear = year;
    chain.qualitySegments[chain.qualitySegments.length - 1].endYear = year;
    chain.hashes.annualGrowthHash = sha256CanonicalLocale(chain.annualGrowthPct);
    chain.hashes.observationContractHash = sha256CanonicalLocale(chain.observationsByYear);
}

/** @param {any} _chain @param {any} lieferung @returns {Record<string, any>} */
export function zeileBerechnen(_chain, lieferung) {
    const observation = lohnBeobachtung(lieferung.jahr, { indexLevel: lieferung.werte.indexstand, annualChangePct: lieferung.werte.veraenderung });
    if (!(observation.sourceObservation.indexLevel > 0)) throw new Error('Lohnindex muss positiv sein.');
    return { observationsByYear: observation, annualGrowthPct: observation.valuePct };
}

/**
 * Gespeicherter Stand: Veränderung und amtlicher Indexstand aus der Kette; Basis bei angehängten Jahren aus dem
 * Fortschreibungsblock, im Grundbestand aus der festgeschriebenen Destatis-Seite.
 * @param {any} chain @param {number} year @param {string} root
 */
export function gespeichert(chain, year, root) {
    const veraenderung = chain.annualGrowthPct[year];
    if (!Number.isFinite(veraenderung)) return null;
    const indexstand = chain.observationsByYear[year]?.sourceObservation?.indexLevel;
    const eintrag = chain.fortschreibung?.lieferungen?.find(item => item.jahr === year);
    const basis = eintrag ? eintrag.basis?.indexstand : Number.isFinite(indexstand) ? grundbestandBasis(root) : undefined;
    return { veraenderung, indexstand, basis: { indexstand: basis } };
}

/** Indexbasis der festgeschriebenen Destatis-Seite, z. B. 2025=100. @param {string} root */
function grundbestandBasis(root) {
    const match = fs.readFileSync(path.join(root, ORIGINAL_HTML), 'utf8').match(/(\d{4})\s*=\s*100/);
    return match ? `${match[1]}=100` : undefined;
}

/** @param {any} lieferung @returns {{regel: string, ok: boolean, text: string}[]} */
export function plausibilitaet(lieferung) {
    const { indexstand, veraenderung } = lieferung.werte;
    const vorjahr = lieferung.anschluss.werte.indexstand;
    const ausIndex = ((indexstand / vorjahr) - 1) * 100;
    const abstand = Math.abs(ausIndex - veraenderung);
    return [{
        regel: 'Index Y/Y−1 gegen Rate, Abstand höchstens 0,1',
        ok: abstand <= 0.1,
        text: `Index ${indexstand}/${vorjahr} ergibt ${ausIndex.toFixed(3)} %, gemeldet ${veraenderung} %, Abstand ${abstand.toFixed(3)}`
    }];
}

/** @param {string} value */
function germanNumber(value) {
    const normalized = value.replace(/<[^>]+>/g, '').replace(/&nbsp;/g, ' ').replace(/&minus;/g, '-').replace(/&amp;/g, '&')
        .trim().replace(/\s+/g, '').replace(',', '.');
    if (!normalized || normalized === '-') return null;
    const parsed = Number(normalized);
    return Number.isFinite(parsed) ? parsed : null;
}

/**
 * Lieferung Y aus der festgeschriebenen Destatis-Seite (Rückwärtsprobe, offline).
 * @param {string} root @param {number} year
 */
export function lieferungAusOriginalen(root, year) {
    const original = fs.readFileSync(path.join(root, ORIGINAL_HTML));
    const rows = new Map([...original.toString('utf8').matchAll(ROW_PATTERN)].map(match => [Number(match[1]), match]));
    const werteFuer = y => {
        const row = rows.get(y);
        if (!row) throw new Error(`Destatis-Lohnindex: Jahr ${y} fehlt.`);
        return { indexstand: germanNumber(row[2]), veraenderung: germanNumber(row[3]) };
    };
    const chain = lesen(root);
    const destatis = chain.sourceFiles[1];
    return lieferungBauen({
        kette: KETTE.id,
        jahr: year,
        werte: werteFuer(year),
        einheit: einheitenFuer(KETTE, werteFuer(year)),
        anschluss: { jahr: year - 1, werte: werteFuer(year - 1) },
        perioden: KETTE.periodenFuer(year),
        basis: { indexstand: grundbestandBasis(root) },
        quelle: {
            name: 'Destatis, Index der durchschnittlichen Bruttomonatsverdienste ohne Sonderzahlungen, Jahre',
            url: destatis.sourceUrl,
            abrufdatum: destatis.retrievedAt,
            veroeffentlichungsstand: destatis.sourcePublishedAsOf
        },
        methode: 'aus Original: Indexstand und veröffentlichte Veränderung zum Vorjahr aus der festgeschriebenen Destatis-Tabelle',
        lieferant: 'skript',
        status: 'endgueltig',
        rohdateien: [{
            datei: 'rohauszug-destatis-verdienste.html', inhalt: Buffer.from(`${rows.get(year - 1)[0]}\n${rows.get(year)[0]}\n`, 'utf8'), art: 'auszug',
            originalDatei: ORIGINAL_HTML, originalSha256: sha256(original)
        }]
    });
}
