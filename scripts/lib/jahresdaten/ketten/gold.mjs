/**
 * Kette Gold (gold-german-investor-chain): Rechenregel, Modultext und Lieferung aus den Originalen.
 *
 * Rechenregel Jahr Y (ab 2000): Goldpreis in EUR je Feinunze = Weltbank-Jahresdurchschnitt USD je
 * Feinunze / Jahresdurchschnitt USD je EUR (Bundesbank/EZB); Rendite = (Niveau Y / Niveau Y−1 − 1) × 100.
 * Das Bauskript nutzt dieselben Funktionen.
 */
import fs from 'node:fs';
import path from 'node:path';
import { jsonAusModul } from '../modultext.mjs';
import { sha256, sha256CanonicalCodepoint } from '../kanonisch.mjs';
import { einheitenFuer, lieferungBauen } from '../lieferung.mjs';
import { readXlsxSheetRows } from '../xlsx.mjs';

const MODUL = 'app/simulator/gold-german-investor-chain.js';
const START = 'export const GOLD_GERMAN_INVESTOR_CHAIN = deepFreeze(';
const ENDE = ');\n\nexport const GOLD_GERMAN_INVESTOR_ANNUAL_RETURNS';
const DATEN = 'data/historical/gold-german-investor-chain/originals';
const SAMPLING = /^all \d+ annual returns/;

export const KETTE = Object.freeze({
    id: 'gold-german-investor-chain',
    seriesId: 'gold_eur_perf',
    label: 'Gold',
    dateien: Object.freeze([MODUL]),
    jahresfelder: Object.freeze(['annualReturnsPct', 'sourceObservations.bundesbankUsdPerEur', 'sourceObservations.worldBankGoldUsdPerTroyOunce']),
    serienfeld: 'annualReturnsPct',
    periodenFuer: jahr => Object.freeze({ werte: String(jahr), anschluss: String(jahr - 1) }),
    werte: Object.freeze({ goldUsdJeUnze: { einheit: 'usd_je_unze' }, usdJeEur: { einheit: 'usd_je_eur' } }),
    beschreibung: Object.freeze({
        goldUsdJeUnze: 'USD je Feinunze, Jahresdurchschnitt (Weltbank Pink Sheet, nominal)',
        usdJeEur: 'USD je EUR, Jahresdurchschnitt der EZB-Referenzkurse (Bundesbank)'
    }),
    anschluss: Object.freeze({
        toleranz: Object.freeze({ goldUsdJeUnze: 0.005, usdJeEur: 0.00005 }),
        regel: 'Goldpreis und Kurs Y−1 gegen die gespeicherten Quellwerte Y−1; Toleranz halbe letzte Stelle (0,005 USD, 0,00005 USD/EUR)'
    })
});

/** @param {string} root @returns {any} */
export function lesen(root) {
    return jsonAusModul(root, MODUL, START, ENDE);
}

/** @param {any} artifact @returns {Map<string, string>} */
export function schreiben(artifact) {
    return new Map([[MODUL, `/**
 * Generated by scripts/build-gold-german-investor-chain.mjs.
 * Do not edit by hand.
 */
"use strict";

function deepFreeze(value, seen = new WeakSet()) {
    if (value === null || typeof value !== 'object' || seen.has(value)) return value;
    seen.add(value);
    for (const child of Object.values(value)) deepFreeze(child, seen);
    return Object.freeze(value);
}

export const GOLD_GERMAN_INVESTOR_CHAIN = deepFreeze(${JSON.stringify(artifact, null, 2)});

export const GOLD_GERMAN_INVESTOR_ANNUAL_RETURNS =
    GOLD_GERMAN_INVESTOR_CHAIN.annualReturnsPct;
`]]);
}

/** Goldniveau in EUR je Feinunze (Bau und Fortschreibung). @param {number} goldUsdPerTroyOunce @param {number} usdPerEur */
export function goldEurJeUnze(goldUsdPerTroyOunce, usdPerEur) {
    return goldUsdPerTroyOunce / usdPerEur;
}

/**
 * Jahresrendite aus zwei Niveaus in Prozent (Bau und Fortschreibung); −0 wird 0.
 * @param {number} currentLevel @param {number} previousLevel @param {number} year
 * @param {(message: string, details?: object) => never} fail
 */
export function goldRenditeProzent(currentLevel, previousLevel, year, fail) {
    const value = ((currentLevel / previousLevel) - 1) * 100;
    if (!Number.isFinite(value) || value <= -100) {
        fail('Calculated annual gold return is invalid', {
            year,
            currentLevel,
            previousLevel,
            value
        });
    }
    return Object.is(value, -0) ? 0 : value;
}

const failHard = (message, details) => { throw new Error(`${message} ${JSON.stringify(details ?? {})}`); };

/** @param {any} chain @returns {number} */
export function endjahr(chain) {
    return chain.coverage.endYear;
}

/** @param {any} chain @param {number} year */
export function endjahrSetzen(chain, year) {
    chain.coverage.endYear = year;
    chain.coverage.yearCount = year - chain.coverage.startYear + 1;
    const last = list => list[list.length - 1];
    last(chain.returnConvention.timingSegments).endYear = year;
    last(chain.currencyRegimes).endYear = year;
    last(chain.qualitySegments).endYear = year;
    chain.monteCarloQualification.samplingTreatment = chain.monteCarloQualification.samplingTreatment
        .replace(SAMPLING, `all ${chain.coverage.yearCount} annual returns`);
    chain.hashes.annualReturnHash = sha256CanonicalCodepoint(chain.annualReturnsPct);
}

/** @param {any} _chain @param {any} lieferung @returns {Record<string, number>} */
export function zeileBerechnen(_chain, lieferung) {
    const { werte, anschluss, jahr } = lieferung;
    const rendite = goldRenditeProzent(goldEurJeUnze(werte.goldUsdJeUnze, werte.usdJeEur),
        goldEurJeUnze(anschluss.werte.goldUsdJeUnze, anschluss.werte.usdJeEur), jahr, failHard);
    if (rendite === 0) throw new Error('Unklassifizierte Nullrendite ist im Goldvertrag nicht zulässig.');
    if (!(werte.goldUsdJeUnze > 0) || !(werte.usdJeEur > 0)) throw new Error('Goldpreis und Kurs müssen positiv sein.');
    return {
        annualReturnsPct: rendite,
        'sourceObservations.bundesbankUsdPerEur': werte.usdJeEur,
        'sourceObservations.worldBankGoldUsdPerTroyOunce': werte.goldUsdJeUnze
    };
}

/** @param {any} chain @param {number} year */
export function gespeichert(chain, year) {
    const goldUsdJeUnze = chain.sourceObservations.worldBankGoldUsdPerTroyOunce[year];
    const usdJeEur = chain.sourceObservations.bundesbankUsdPerEur[year];
    return Number.isFinite(goldUsdJeUnze) && Number.isFinite(usdJeEur) ? { goldUsdJeUnze, usdJeEur } : null;
}

/** @param {any} lieferung @returns {{regel: string, ok: boolean, text: string}[]} */
export function plausibilitaet(lieferung) {
    const { werte, anschluss } = lieferung;
    const rendite = ((goldEurJeUnze(werte.goldUsdJeUnze, werte.usdJeEur) / goldEurJeUnze(anschluss.werte.goldUsdJeUnze, anschluss.werte.usdJeEur)) - 1) * 100;
    return [
        { regel: 'Rendite −40 bis +60 %', ok: rendite >= -40 && rendite <= 60, text: `Rendite ${rendite.toFixed(2)} %` },
        { regel: 'USD/EUR 0,8–1,6', ok: werte.usdJeEur >= 0.8 && werte.usdJeEur <= 1.6, text: `USD/EUR ${werte.usdJeEur}` }
    ];
}

/**
 * Lieferung Y aus der Bundesbank-Kursdatei und der Weltbank-Arbeitsmappe (Rückwärtsprobe, offline).
 * @param {string} root @param {number} year
 */
export function lieferungAusOriginalen(root, year) {
    const chain = lesen(root);
    const usdQuelle = chain.sourceFiles.bundesbankUsdEur;
    const goldQuelle = chain.sourceFiles.worldBankGoldUsd;
    const usdOriginal = fs.readFileSync(path.join(root, DATEN, usdQuelle.fileName));
    const goldOriginal = fs.readFileSync(path.join(root, DATEN, goldQuelle.fileName));
    const [kopf, ...zeilen] = usdOriginal.toString('utf8').replace(/^﻿/, '').split(/\r?\n/).filter(Boolean);
    const spalten = kopf.split(';');
    const usdZeile = y => {
        const zeile = zeilen.find(line => line.split(';')[spalten.indexOf('TIME_PERIOD')] === String(y));
        if (!zeile) throw new Error(`Bundesbank USD/EUR: Jahr ${y} fehlt.`);
        return { zeile, wert: Number(zeile.split(';')[spalten.indexOf('OBS_VALUE')]) };
    };
    const rows = readXlsxSheetRows(goldOriginal, 'Annual Prices (Nominal)');
    const kopfIndex = rows.findIndex(row => row.includes('Gold'));
    const goldSpalte = rows[kopfIndex].indexOf('Gold');
    const goldZelle = y => {
        const row = rows.slice(kopfIndex + 2).find(candidate => Number(candidate[0]) === y);
        if (!row) throw new Error(`Weltbank Gold: Jahr ${y} fehlt.`);
        return { text: row[goldSpalte], wert: Number(row[goldSpalte]) };
    };
    const werteFuer = y => ({ goldUsdJeUnze: goldZelle(y).wert, usdJeEur: usdZeile(y).wert });
    const goldAuszug = ['Jahr;Gold (USD/troy oz), Blatt Annual Prices (Nominal)', ...[year - 1, year].map(y => `${y};${goldZelle(y).text}`)].join('\n');
    return lieferungBauen({
        kette: KETTE.id,
        jahr: year,
        werte: werteFuer(year),
        einheit: einheitenFuer(KETTE, { goldUsdJeUnze: true, usdJeEur: true }),
        anschluss: { jahr: year - 1, werte: werteFuer(year - 1) },
        perioden: KETTE.periodenFuer(year),
        quelle: {
            name: 'Weltbank Commodity Price Data (Pink Sheet), Gold; Bundesbank BBEX3 USD/EUR Jahresdurchschnitt',
            url: goldQuelle.sourceUrl,
            abrufdatum: '2026-07-30',
            veroeffentlichungsstand: `Weltbank ${goldQuelle.dataAsOf}; Bundesbank ${usdQuelle.dataAsOf}`
        },
        methode: 'aus Original: Jahresdurchschnitte aus der festgeschriebenen Weltbank-Arbeitsmappe und der Bundesbank-Kursdatei',
        lieferant: 'skript',
        status: 'endgueltig',
        rohdateien: [
            { datei: 'rohauszug-weltbank-gold.csv', inhalt: Buffer.from(`${goldAuszug}\n`, 'utf8'), art: 'auszug', originalDatei: `${DATEN}/${goldQuelle.fileName}`, originalSha256: sha256(goldOriginal) },
            { datei: 'rohauszug-bundesbank-usd-eur.csv', inhalt: Buffer.from(`${[kopf, usdZeile(year - 1).zeile, usdZeile(year).zeile].join('\n')}\n`, 'utf8'), art: 'auszug', originalDatei: `${DATEN}/${usdQuelle.fileName}`, originalSha256: sha256(usdOriginal) }
        ]
    });
}
